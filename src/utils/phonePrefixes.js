export const removePhonePrefix = (phone) => {
  if (!phone) return phone;

  // ordenar prefijos por longitud (los más largos primero)
  const sortedPrefixes = [...phonePrefixes].sort(
    (a, b) => b.code.length - a.code.length,
  );

  const prefix = sortedPrefixes.find((p) =>
    phone.startsWith(p.code.replace("-", "")),
  );

  if (!prefix) return phone;

  const cleanCode = prefix.code.replace("-", "");

  return phone.replace(cleanCode, "");
};

export const parsePhone = (phone) => {
  const sortedPrefixes = [...phonePrefixes].sort(
    (a, b) => b.code.length - a.code.length,
  );

  const prefix = sortedPrefixes.find((p) =>
    phone.startsWith(p.code.replace("-", "")),
  );

  if (!prefix) {
    return { prefix: null, number: phone };
  }

  const cleanCode = prefix.code.replace("-", "");

  return {
    prefix,
    number: phone.replace(cleanCode, ""),
  };
};
